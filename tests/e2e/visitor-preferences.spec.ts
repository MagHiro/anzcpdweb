import { test, expect } from "@playwright/test";

test.use({ timezoneId: "Pacific/Auckland" });

test("the time zone bubble animates both ways and respects reduced motion", async ({ page }) => {
  await page.goto("/");
  const bubble = page.getByRole("button", { name: "Choose timezone" });
  const panel = page.locator(".visitor-preferences-panel");
  const toggle = () => bubble.evaluate(button => {
    const panel = document.getElementById(button.getAttribute("aria-controls")!)!;
    const animations: string[] = [];
    return new Promise<string[]>(resolve => {
      panel.addEventListener("transitionrun", event => animations.push(event.propertyName));
      (button as HTMLButtonElement).click();
      requestAnimationFrame(() => requestAnimationFrame(() => resolve(animations)));
    });
  });
  await expect(bubble).toContainText("Pacific/Auckland");
  expect(await toggle()).toContain("opacity");
  await expect(panel).toHaveCSS("opacity", "1");
  expect(await toggle()).toContain("opacity");
  await expect(panel).toBeHidden();
  await page.emulateMedia({ reducedMotion: "reduce" });
  expect(await toggle()).toEqual([]);
  await expect(panel).toBeVisible();
  expect(await toggle()).toEqual([]);
  await expect(panel).toBeHidden();
});

test("timezone settings open only on request and remember the selected timezone", async ({ page }) => {
  await page.clock.install();
  await page.goto("/");
  const panel = page.getByRole("region", { name: "Time zone", exact: true });
  const bubble = page.getByRole("button", { name: "Choose timezone", exact: true });
  const search = panel.getByRole("combobox", { name: "Time zone for online classes" });
  await expect(bubble).toContainText("Pacific/Auckland");
  await page.clock.runFor(800);
  await expect(bubble).toHaveAttribute("aria-expanded", "false");
  await expect(panel).toHaveCount(0);
  await bubble.click();
  await expect(panel).toBeVisible();
  await expect(panel.getByLabel("Country", { exact: true })).toHaveCount(0);
  await expect(search).toHaveAttribute("placeholder", /^Automatic/);
  await expect(panel.getByRole("listbox")).toHaveCount(0);
  await search.focus();
  await page.keyboard.type("Perth");
  await expect(page.getByRole("listbox").getByRole("option")).toHaveCount(1);
  await page.getByRole("option", { name: "Australia/Perth" }).click();
  await expect(bubble).toContainText("Australia/Perth");
  await expect(panel.getByRole("link")).toHaveCount(0);
  await panel.getByRole("button", { name: "Close time zone settings" }).click();
  await expect(panel).toHaveCount(0);
  await page.reload();
  await expect(bubble).toContainText("Australia/Perth");
  await page.clock.runFor(800);
  await expect(panel).toHaveCount(0);
  await bubble.click();
  await expect(panel).toBeVisible();
  await expect(search).toHaveAttribute("placeholder", "Australia/Perth");
  await search.click();
  await page.getByRole("option", { name: /^Automatic/ }).click();
  await expect(bubble).toContainText("Pacific/Auckland");
  await page.keyboard.press("Escape");
  await expect(panel).toHaveCount(0);
  await expect(bubble).toBeFocused();
  await page.setViewportSize({ width: 390, height: 844 });
  await bubble.click();
  await expect(panel).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await search.click();
  const results = panel.getByRole("listbox");
  await expect(results).toBeVisible();
  await expect(panel.getByRole("combobox")).toHaveCount(1);
  await search.fill("not a time zone");
  await expect(panel.getByRole("status")).toHaveText("No matching time zones");
  await search.fill("Singapore");
  await search.press("Enter");
  await expect(search).toHaveAttribute("placeholder", "Asia/Singapore");
  await expect(results).toHaveCount(0);
  await expect(search).toBeFocused();
});
