import { randomUUID } from "node:crypto";
import { test, expect } from "@playwright/test";
import { eq } from "drizzle-orm";
import { bookings, categories, classes, emailOutbox } from "@/db/schema";
import { getDb } from "@/lib/db";

test("admin can browse class counts, inspect participants and combine booking filters", async ({ page }) => {
  test.skip(!process.env.ADMIN_TEST_EMAIL || !process.env.ADMIN_TEST_PASSWORD || !process.env.DATABASE_URL, "Isolated database and local admin required");
  const db = getDb();
  const key = randomUUID();
  const [category] = await db.insert(categories).values({ country: "AU", name: "Roster test", slug: key }).returning();
  const startAt = new Date(Date.now() + 86400000);
  const [activity] = await db.insert(classes).values({ country: "AU", categoryId: category.id, title: `Roster ${key}`, slug: key, shortDescription: "Test", fullDescription: "Test", startAt, endAt: new Date(startAt.getTime() + 3600000), timezone: "Australia/Sydney", bookingOpensAt: new Date(), bookingClosesAt: startAt, deliveryFormat: "ONLINE", priceMinorUnits: 0, currency: "AUD", seatCapacity: 10, status: "PUBLISHED" }).returning();
  await db.insert(bookings).values((["CONFIRMED", "PARTIALLY_REFUNDED", "PENDING_PAYMENT", "CANCELLED"] as const).map((status, index) => ({ classId: activity.id, fullName: `Roster attendee ${index}`, email: `attendee${index}@example.com`, country: "AU" as const, status, amountSnapshot: 0, currencySnapshot: "AUD", classTitleSnapshot: activity.title, timezoneSnapshot: activity.timezone, termsAcceptedAt: new Date(), refundPolicyAcceptedAt: new Date(), idempotencyKey: randomUUID() })));
  try {
    const { version } = await (await page.request.get("/api/version")).json();
    const login = await page.request.post("/api/auth/login", { data: { email: process.env.ADMIN_TEST_EMAIL, password: process.env.ADMIN_TEST_PASSWORD }, headers: { origin: "http://127.0.0.1:3100", "x-app-version": version } });
    expect(login.ok()).toBe(true);
    await page.goto(`/admin/bookings?view=classes&classSearch=${key}`);
    const classRow = page.getByRole("row").filter({ hasText: activity.title });
    await expect(classRow).toContainText("2 / 10");
    await expect(classRow.getByRole("cell", { name: "1", exact: true })).toBeVisible();
    await page.getByRole("combobox", { name: "Class period" }).selectOption("past");
    await page.getByRole("button", { name: "Filter", exact: true }).click();
    await expect(page.getByText("No classes found.")).toBeVisible();
    await page.getByRole("combobox", { name: "Class period" }).selectOption("upcoming");
    await page.getByRole("button", { name: "Filter", exact: true }).click();
    await classRow.getByRole("link", { name: `View participants for ${activity.title}` }).click();
    await expect(page.getByRole("region", { name: "Selected class" })).toContainText("2 participants / 10 capacity");
    await expect(page.getByRole("link", { name: "Roster attendee 0", exact: true })).toBeVisible();
    await expect(page.getByRole("link", { name: "Roster attendee 1", exact: true })).toBeVisible();
    await expect(page.getByRole("link", { name: "Roster attendee 2", exact: true })).toHaveCount(0);
    await expect(page.getByRole("columnheader", { name: "Class", exact: true })).toHaveCount(0);
    const exported = await page.request.get(`/api/admin/bookings/export?classId=${activity.id}`);
    expect(exported.status()).toBe(200);
    const csv = await exported.text();
    expect(csv).toContain("Roster attendee 0");
    expect(csv).not.toContain("Roster attendee 2");
    page.once("dialog", dialog => dialog.accept());
    await page.getByRole("row").filter({ hasText: "Roster attendee 0" }).getByRole("button", { name: /Resend .* reminder/ }).click();
    await expect(page.getByRole("row").filter({ hasText: "Roster attendee 0" }).getByText("Reminder queued.")).toBeVisible();
    await expect(page.getByRole("row").filter({ hasText: "Roster attendee 0" })).toContainText("Pending");
    const [participant] = await db.select().from(bookings).where(eq(bookings.classId, activity.id));
    const { version: currentVersion } = await (await page.request.get("/api/version")).json();
    const attendanceTooEarly = await page.request.post("/api/admin/bookings", { data: { action: "attendance", bookingId: participant.id, attendance: "ATTENDED" }, headers: { origin: "http://127.0.0.1:3100", "x-app-version": currentVersion } });
    expect(attendanceTooEarly.status()).toBe(400);
    await db.update(classes).set({ startAt: new Date(Date.now() - 3600000) }).where(eq(classes.id, activity.id));
    await page.reload();
    const attendeeRow = page.getByRole("row").filter({ hasText: "Roster attendee 0" });
    await attendeeRow.getByRole("combobox", { name: "Attendance", exact: true }).selectOption("ATTENDED");
    await expect(attendeeRow.getByText("Attendance saved.")).toBeVisible();
    await page.reload();
    await expect(attendeeRow.getByRole("combobox", { name: "Attendance", exact: true })).toHaveValue("ATTENDED");
    await page.getByRole("combobox", { name: "Booking status", exact: true }).selectOption("PENDING_PAYMENT");
    await page.getByRole("button", { name: "Filter", exact: true }).click();
    await expect(page.getByRole("link", { name: "Roster attendee 2", exact: true })).toBeVisible();
    await expect(page.getByRole("link", { name: "Roster attendee 0", exact: true })).toHaveCount(0);
    await page.getByRole("textbox", { name: "Search attendee or email" }).fill("no-matching-attendee");
    await page.getByRole("button", { name: "Filter", exact: true }).click();
    await expect(page.getByText("No bookings match these filters.")).toBeVisible();
    await page.goto("/admin/bookings?classId=not-a-uuid");
    await expect(page.getByText("No bookings match these filters.")).toBeVisible();
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto(`/admin/bookings?classId=${activity.id}&status=participants`);
    await expect(page.getByRole("combobox", { name: "Class", exact: true })).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  } finally {
    await db.delete(emailOutbox).where(eq(emailOutbox.recipientEmail, "attendee0@example.com"));
    await db.delete(bookings).where(eq(bookings.classId, activity.id));
    await db.delete(classes).where(eq(classes.id, activity.id));
    await db.delete(categories).where(eq(categories.id, category.id));
  }
});
